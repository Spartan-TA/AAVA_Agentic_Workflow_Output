# Monday Morning Coffee - An Office Poem
# Written in humorous free verse style

poem = '''
Monday Morning Coffee

The alarm clock screams at 6 AM,
A cruel reminder that the weekend's dead,
I stumble to the kitchen like a zombie,
Reaching for my caffeinated salvation.

The coffee maker gurgles and hisses,
Like an old dragon brewing liquid courage,
While I stand there in my wrinkled pajamas,
Contemplating the existential dread of spreadsheets.

First sip - bitter as my Monday mood,
Second sip - slightly more human,
Third sip - I remember my own name,
Fourth sip - I might actually survive this day.

By cup number two, I'm ready to face
The endless emails marked "URGENT!!!",
The meetings that could have been emails,
And Karen from accounting's passive-aggressive notes.

Oh Monday morning coffee,
You beautiful, bitter friend,
Without you, I'd still be under my desk,
Whimpering softly about quarterly reports.

So here's to you, dark liquid motivation,
Transformer of grumpy humans,
Maker of miracles,
Savior of corporate souls.

Amen.
'''

print(poem)