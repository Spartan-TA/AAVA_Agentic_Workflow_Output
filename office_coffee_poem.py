# Office Coffee Limericks
# An entertaining poem about coffee culture in the corporate office

poem = '''
There once was a worker named Pete,
Who lived on caffeine, oh so sweet,
He'd brew cup by cup,
Till his energy was up,
And made deadlines he'd always meet!

The office coffee machine so grand,
Is the lifeline of our working band,
With a gurgle and hiss,
It brings caffeinated bliss,
The best invention in all the land!

When Monday morning blues arrive,
We need our coffee to feel alive,
That first precious sip,
Gives our spirits a flip,
And helps our productivity thrive!
'''

print(poem)